"""菜品画像。

判断「这是什么菜」的能力集中在这里，与「怎么求解组合」分开。

抽出这个模块的原因：`nutrition_solver` 是全项目依赖最广的模块，而类别
判定被十几个调用方直接使用。如果它继续以私有函数（`_category_of`）的形式
留在solver 里，改动类别的判定规则就会牵动求解逻辑——实测踩过两次：

  - 关键词表顺序让「纯牛奶」含"牛"、「热浓浓抹茶牛奶」含"蛋"（浓**蛋**绿）
    先命中"蛋白"，于是「可乐大杯 + 纯牛奶」通过了「必须含主食或蛋白」
    的校验，给 4 岁孩子推荐了汽水加牛奶
  - 修好类别后，smoke_test 的基线首解随之变化（513kcal/钠173mg →
    443kcal/钠438mg），因为更多组合变得合法

判定规则本身与求解无关，回答的是"这份数据能不能用""这是什么类别""算不算
一餐"，因此独立成层。
"""

from __future__ import annotations

# 餐品类别，按实测营养表名称归类。
#
# 顺序即优先级：先匹配到的类别生效，所以奶品/饮品必须排在"蛋白"之前。
# 反例（实测踩过）：「纯牛奶」含"牛"、「热浓浓抹茶牛奶」含"蛋"（浓**蛋**绿），
# 若"蛋白"规则先命中，纯牛奶会被判成蛋白类，于是
#「可乐大杯 + 纯牛奶」通过了"必须含主食或蛋白"的校验——
# 给 4 岁孩子推荐汽水加牛奶。奶品与饮品必须优先判定。
CATEGORY_RULES: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("主食", ("麦满分", "汉堡", "堡", "卷", "麦香鱼", "三件套", "四件套", "巨无霸")),
    ("奶品", ("牛奶", "纯悦", "豆浆", "燕麦", "乳酸")),
    (
        "饮品",
        (
            "可乐", "雪碧", "红茶", "绿茶", "果汁", "矿泉水", "苏打", "柠",
            "美汁源", "旋酷", "阳光橙", "苹果片", "黑巧", "怡泉", "伯爵",
        ),
    ),
    (
        "咖啡",
        (
            "咖啡", "美式", "拿铁", "卡布", "摩卡", "焦糖", "阿芙佳朵", "奶铁",
            "朱古力",
        ),
    ),
    (
        "甜品",
        (
            "派", "新地", "冰淇淋", "旋风", "雪冰", "奶冻", "圣代", "拉明顿",
            "苹板", "蜜汁", "奶冻款", "爆珠款",
        ),
    ),
    (
        "配菜",
        (
            "薯条", "玉米", "沙拉", "蔬菜", "小食", "拼盘", "薯饼", "油条",
            "香肠",
        ),
    ),
    ("蛋白", ("鸡", "牛", "猪", "鱼", "虾", "蛋", "肉", "翅", "腿", "支撑Pro")),
)

# 一餐的构成成分：必须有其中之一，否则只是"几样东西凑在一起"。
MEAL_CATEGORIES: frozenset[str] = frozenset({"主食", "蛋白"})

# 类别在页面上的视觉标识，供生成器使用。
CATEGORY_ICON: dict[str, str] = {
    "主食": "◆",
    "蛋白": "●",
    "配菜": "■",
    "饮品": "○",
    "咖啡": "○",
    "奶品": "○",
    "甜品": "◇",
}


def category_of(name: str) -> str:
    """按名称关键词判定餐品类别，未命中返回空串。

    Args:
        name: 餐品名称，取自官方营养表或门店菜单。

    Returns:
        类别名；未命中任何规则时返回空串（不是None，便于直接做相等判断）。
    """
    if not name:
        return ""
    for category, keywords in CATEGORY_RULES:
        if any(k in name for k in keywords):
            return category
    return ""


def is_meal_item(name: str) -> bool:
    """该餐品是否属于正餐主体（主食或蛋白）。"""
    return category_of(name) in MEAL_CATEGORIES


def has_meal_component(names: list[str]) -> bool:
    """一组餐品里是否含正餐主体，即是否"像一餐"。"""
    return any(is_meal_item(n) for n in names)


def categories_of(names: list[str]) -> list[str]:
    """批量取类别，顺序与输入一致。"""
    return [category_of(n) for n in names]


def icon_for(name: str) -> str:
    """类别对应的显示符号，未识别时返回中点。"""
    return CATEGORY_ICON.get(category_of(name), "·")